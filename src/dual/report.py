"""The bar table from the measure job's summaries. Pure: no torch.

`python -m dual.report runs/` reads every `runs/measure/*/summary.json` (each a list of
per-epoch summaries) and prints markdown: the bar on content frames, on all frames, and
each run's best epoch.
"""

from __future__ import annotations

import json
import pathlib
import sys
from collections.abc import Sequence
from typing import Any

COLUMNS = (
    "run",
    "base",
    "slice",
    "epoch",
    "median gap",
    "median floor",
    "p90 gap",
    "p90 floor",
    "pass",
    "door",
    "tape gap",
)


def passes(b: dict[str, Any]) -> bool:
    return bool(b["median_gap"] <= b["median_floor"] and b["p90_gap"] <= b["p90_floor"])


def _row(s: dict[str, Any], key: str) -> str:
    b = s[key]
    door, tape = (
        ("door_median", "tape_gap_median")
        if key == "content"
        else ("door_all_median", "tape_gap_all_median")
    )
    cells = [
        s["run"] or "bare",
        s["base"],
        f"1/{s['slice']}" if s.get("slice") else "-",
        str(s["epoch"]),
        *(
            f"{b[k]:.3f}"
            for k in ("median_gap", "median_floor", "p90_gap", "p90_floor")
        ),
        "yes" if passes(b) else "no",
        f"{s.get(door, s.get('door_median', float('nan'))):.3f}",
        f"{s.get(tape, s.get('tape_gap_median', float('nan'))):.3f}",
    ]
    return "| " + " | ".join(cells) + " |"


def table(summaries: Sequence[dict[str, Any]], key: str = "content") -> str:
    head = "| " + " | ".join(COLUMNS) + " |"
    rule = "|" + "|".join("---" for _ in COLUMNS) + "|"
    return "\n".join([head, rule, *(_row(s, key) for s in summaries)])


def _ratio(s: dict[str, Any]) -> float:
    b = s["content"]
    floor = float(b["median_floor"])
    return float(b["median_gap"]) / floor if floor > 0 else float("inf")


def best(summaries: Sequence[dict[str, Any]]) -> list[dict[str, Any]]:
    """Per (run, base), the epoch to report: one that passes the bar (median and p90)
    over one that does not, then the smallest median gap / median floor."""

    def key(s: dict[str, Any]) -> tuple[bool, float]:
        return (not passes(s["content"]), _ratio(s))

    picked: dict[tuple[str, str], dict[str, Any]] = {}
    for s in summaries:
        k = (s["run"] or "", s["base"])
        if k not in picked or key(s) < key(picked[k]):
            picked[k] = s
    return [picked[k] for k in sorted(picked)]


def read(root: pathlib.Path) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    seen: dict[tuple[str, str, int], pathlib.Path] = {}
    for path in sorted(root.glob("measure/*/summary.json")):
        for s in json.loads(path.read_text()):
            k = (s["run"] or "", s["base"], int(s["epoch"]))
            if k in seen:
                raise ValueError(
                    f"two summaries for run={k[0] or 'bare'!r} base={k[1]!r} "
                    f"epoch={k[2]}: {seen[k]} and {path}"
                )
            seen[k] = path
            out.append(s)
    out.sort(key=lambda s: (s["base"], s["run"] or "", s["epoch"]))
    return out


def render(summaries: Sequence[dict[str, Any]]) -> str:
    return "\n".join(
        [
            "# The bar",
            "",
            "gap = KL(typed || A), floor = KL(A || B), door = KL(C || A), "
            "tape gap = KL(typed || tape); medians and p90s over the holdout's pupil "
            "turns. Pass: median gap <= median floor and p90 gap <= p90 floor.",
            "Generated by `make bar` (`python -m dual.report runs/`).",
            "",
            "## content frames (the bar)",
            "",
            table(summaries, "content"),
            "",
            "## all frames",
            "",
            table(summaries, "all"),
            "",
            "## best epoch per run (content frames)",
            "",
            table(best(summaries), "content"),
            "",
        ]
    )


def main(argv: Sequence[str] | None = None) -> None:
    args = list(sys.argv[1:] if argv is None else argv)
    root = pathlib.Path(args[0] if args else "runs")
    sys.stdout.write(render(read(root)))


if __name__ == "__main__":
    main()
